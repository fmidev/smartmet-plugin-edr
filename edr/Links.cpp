Json::Value links_json(const Links& links)
{
  auto ret = Json::Value(Json::ValueType::arrayValue);
  for (const auto& link : links)
  {
    auto value = Json::Value(Json::ValueType::objectValue);
    value["href"] = Json::Value(link.href);
    value["rel"] = Json::Value(link.rel);
    value["type"] = Json::Value(link.type);
    ret.append(value);
  }
  return ret;
}

std::string link_header(const Links& links)
{
  std::string ret;
  for (const auto& link : links)
  {
    if (!ret.empty())
      ret += ", ";
    // The URLs are generated by the plugin and the request parameters in them are URL
    // encoded, they cannot contain '>'
    ret += "<" + link.href + ">; rel=\"" + link.rel + "\"";
    if (!link.type.empty())
      ret += "; type=\"" + link.type + "\"";
  }
  return ret;
}

